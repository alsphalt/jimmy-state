/**
 * Generates the Vercel function files under /api from the Express route table.
 *
 * Why this exists: Vercel's standalone functions do not honour a catch-all filename.
 * `api/[...route].js` was matched as a single segment, so `/api/health` worked while
 * `/api/music/search` returned the platform's own 404 — the bug this project shipped
 * with. Each route shape therefore needs its own file.
 *
 * The route table in server/app.js stays the single source of truth; run this after
 * adding or changing a route.
 *
 *   node scripts/make-api-routes.mjs           # write the files
 *   node scripts/make-api-routes.mjs --check   # fail if api/ is out of date
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const APP = path.join(ROOT, 'server', 'app.js')
const API_DIR = path.join(ROOT, 'api')
const check = process.argv.includes('--check')

/** `/api/music/track/:id(\w[\w-]{10})` -> `/music/track/[id]` */
export function toFunctionPath(route) {
  return route
    .replace(/^\/api/, '')
    .split('/')
    .map((segment) => {
      if (!segment.startsWith(':')) return segment
      const name = segment.slice(1).replace(/\(.*$/, '')
      return `[${name}]`
    })
    .join('/')
}

/** Every /api route declared in the Express app. */
export function collectRoutes(code) {
  const routes = new Set()
  const re = /app\.(?:get|post|put|delete|patch|all)\(\s*['"`](\/api\/[^'"`]*)['"`]/g
  let match
  while ((match = re.exec(code))) routes.add(match[1])
  return [...routes].sort()
}

export function plan(code) {
  return collectRoutes(code).map((route) => {
    const fnPath = toFunctionPath(route) // /music/search
    const relFile = `${fnPath.replace(/^\//, '')}.js` // music/search.js
    const depth = fnPath.split('/').filter(Boolean).length - 1
    const body = `// Generated by scripts/make-api-routes.mjs from ${route}
// Vercel functions have no catch-all; each route shape needs its own file.
import handler from '${'../'.repeat(depth + 1)}server/handler.js'

export const config = { api: { bodyParser: false, sizeLimit: '8mb' } }
export default handler
`
    return { route, fnPath, relFile, file: path.join(API_DIR, relFile), body }
  })
}

const routes = plan(fs.readFileSync(APP, 'utf8'))
const stale = []
let written = 0

for (const entry of routes) {
  const current = fs.existsSync(entry.file) ? fs.readFileSync(entry.file, 'utf8') : null
  if (current === entry.body) continue
  if (check) {
    stale.push(entry.fnPath)
    continue
  }
  fs.mkdirSync(path.dirname(entry.file), { recursive: true })
  fs.writeFileSync(entry.file, entry.body)
  written += 1
}

// Files with no matching route (e.g. the retired catch-all) must not linger: Vercel
// would publish them as extra endpoints.
if (fs.existsSync(API_DIR)) {
  for (const found of fs.readdirSync(API_DIR, { recursive: true })) {
    const full = path.join(API_DIR, found)
    if (!fs.statSync(full).isFile() || !full.endsWith('.js')) continue
    const relFile = path.relative(API_DIR, full).split(path.sep).join('/')
    if (routes.some((r) => r.relFile === relFile)) continue
    if (check) stale.push(`orphan:${relFile}`)
    else {
      fs.unlinkSync(full)
      written += 1
    }
  }
}

if (check) {
  if (stale.length) {
    console.error(`api/ is out of date (${stale.length}):\n  ${stale.join('\n  ')}`)
    console.error('Run: node scripts/make-api-routes.mjs')
    process.exitCode = 1
  } else {
    console.log(`api/ matches the Express route table (${routes.length} functions)`)
  }
} else {
  console.log(`${routes.length} route shapes, ${written} file(s) changed`)
  routes.forEach((r) => console.log(`  api${r.fnPath}.js  ->  ${r.route}`))
}
