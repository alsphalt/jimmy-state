/**
 * Generates the Vercel function files under /api from the Express route table.
 *
 * Two constraints shaped this:
 *
 * 1. Vercel's standalone functions have no catch-all. `api/[...route].js` is matched as
 *    a SINGLE path segment, so `/api/health` worked while `/api/music/search` returned
 *    the platform's own 404. Each URL depth therefore needs a real file.
 *
 * 2. More files means more build surface and more cold starts. Routes are grouped by
 *    (first segment, depth) and emitted as one dynamic file per group. Dynamic segment
 *    names differ per depth so a file and a directory never share a name.
 *
 * Every generated file delegates to the same Express app, which still routes on the
 * original URL — so a dynamic file can happily serve every sibling route.
 *
 *   node scripts/make-api-routes.mjs           # write the files
 *   node scripts/make-api-routes.mjs --check   # fail if api/ is out of date
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const APP = path.join(ROOT, 'server', 'app.js')
const API_DIR = path.join(ROOT, 'api')
const check = process.argv.includes('--check')

const PARAM_NAMES = ['a', 'b', 'c', 'd']

/** Every /api route declared in the Express app. */
export function collectRoutes(code) {
  const routes = new Set()
  const re = /app\.(?:get|post|put|delete|patch|all)\(\s*['"`](\/api\/[^'"`]*)['"`]/g
  let match
  while ((match = re.exec(code))) routes.add(match[1])
  return [...routes].sort()
}

/**
 * Group routes into function files.
 * `/api/music/search`      -> api/music/[a].js
 * `/api/music/track/:id`   -> api/music/[b]/[c].js
 */
export function plan(code) {
  const groups = new Map()

  for (const route of collectRoutes(code)) {
    const segments = route.replace(/^\/api\//, '').split('/')
    const depth = segments.length
    const first = segments[0]

    // Depth 1 paths are literal files (/api/health); anything deeper becomes dynamic
    // under the first segment, which is itself literal.
    if (depth === 1) {
      groups.set(`${first}::1`, { first, depth: 1, routes: [] })
      groups.get(`${first}::1`).routes.push(route)
      continue
    }
    const key = `${first}::${depth}`
    if (!groups.has(key)) groups.set(key, { first, depth, routes: [] })
    groups.get(key).routes.push(route)
  }

  return [...groups.values()]
    .map(({ first, depth, routes }) => {
      let relFile
      if (depth === 1) relFile = `${first}.js`
      else {
        // Distinct names per depth: [a].js next to [b]/[c].js — never [a].js + [a]/.
        const params = depth === 2 ? [PARAM_NAMES[0]] : [PARAM_NAMES[1], PARAM_NAMES[2]].slice(0, depth - 1)
        relFile = [first, ...params.map((p) => `[${p}]`)].join('/') + '.js'
      }
      const levels = relFile.split('/').length - 1
      const body = `// Generated by scripts/make-api-routes.mjs — serves: ${routes.join(', ')}
// Vercel functions have no catch-all; one file per URL depth is required.
import handler from '${'../'.repeat(levels + 1)}server/handler.js'

export const config = { api: { bodyParser: false, sizeLimit: '8mb' } }
export default handler
`
      return { relFile, routes, file: path.join(API_DIR, relFile), body }
    })
    .sort((a, b) => a.relFile.localeCompare(b.relFile))
}

const planEntries = plan(fs.readFileSync(APP, 'utf8'))
const stale = []
let written = 0

for (const entry of planEntries) {
  const current = fs.existsSync(entry.file) ? fs.readFileSync(entry.file, 'utf8') : null
  if (current === entry.body) continue
  if (check) {
    stale.push(entry.relFile)
    continue
  }
  fs.mkdirSync(path.dirname(entry.file), { recursive: true })
  fs.writeFileSync(entry.file, entry.body)
  written += 1
}

// Files with no matching group (e.g. the retired catch-all) must not linger: Vercel
// would publish them as extra endpoints.
if (fs.existsSync(API_DIR)) {
  for (const found of fs.readdirSync(API_DIR, { recursive: true })) {
    const full = path.join(API_DIR, found)
    if (!fs.statSync(full).isFile() || !full.endsWith('.js')) continue
    const relFile = path.relative(API_DIR, full).split(path.sep).join('/')
    if (planEntries.some((r) => r.relFile === relFile)) continue
    if (check) stale.push(`orphan:${relFile}`)
    else {
      fs.unlinkSync(full)
      written += 1
    }
  }
}

if (check) {
  if (stale.length) {
    console.error(`api/ is out of date (${stale.length}):\n  ${stale.join('\n  ')}`)
    console.error('Run: node scripts/make-api-routes.mjs')
    process.exitCode = 1
  } else {
    console.log(`api/ matches the Express route table (${planEntries.length} functions)`)
  }
} else {
  console.log(`${planEntries.length} function files, ${written} changed`)
  planEntries.forEach((r) => console.log(`  api/${r.relFile}  <-  ${r.routes.join(', ')}`))
}
