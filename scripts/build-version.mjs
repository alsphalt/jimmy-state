/**
 * One version number for three platforms.
 *
 * The website, the installed PWA and the Android APK must agree on what "latest" means,
 * otherwise an APK user is told they are current while the site already shipped a fix.
 * `package.json` is the single source of truth; this script derives everything else:
 *
 *   public/app/version.json      the manifest the app polls to detect an update
 *   android/version.properties   versionName / versionCode read by app/build.gradle
 *
 * Android needs a monotonically increasing integer, not a SemVer string, so the version
 * is folded into `major * 1000000 + minor * 1000 + patch`. That leaves room for 999
 * patches and 999 minor releases before either field bleeds into the next one.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'))

const match = /^(\d+)\.(\d+)\.(\d+)/.exec(pkg.version || '')
if (!match) {
  console.error(`[version] package.json version "${pkg.version}" is not SemVer.`)
  process.exit(1)
}
const [, major, minor, patch] = match.map(Number)
const versionCode = major * 1_000_000 + minor * 1_000 + patch

/** Stable release URL: GitHub serves the asset of the newest release under this name. */
const apkUrl =
  process.env.APK_URL ||
  `https://github.com/${process.env.GITHUB_REPOSITORY || 'alsphalt/jimmy-state'}/releases/latest/download/jimmy-state.apk`

const outDir = path.join(ROOT, 'public', 'app')
const outFile = path.join(outDir, 'version.json')

/**
 * Keep `releasedAt` stable while the version is unchanged. Re-stamping it on every
 * build would make a generated file dirty after each `npm run build` and turn a
 * release commit into noise.
 */
let releasedAt = new Date().toISOString()
try {
  const previous = JSON.parse(fs.readFileSync(outFile, 'utf8'))
  if (previous.version === pkg.version && previous.releasedAt) releasedAt = previous.releasedAt
} catch {
  /* first build */
}

const manifest = {
  name: pkg.name,
  version: pkg.version,
  versionCode,
  releasedAt,
  apkUrl,
  apkSha256: process.env.APK_SHA256 || null,
  minVersionCode: Number(process.env.MIN_VERSION_CODE || 0),
  notes: process.env.RELEASE_NOTES || '',
}

fs.mkdirSync(outDir, { recursive: true })
fs.writeFileSync(outFile, `${JSON.stringify(manifest, null, 2)}\n`)

// The Gradle build reads this file, so `npx cap sync` and `./gradlew assembleRelease`
// produce an APK whose versionCode is the one the manifest above advertises.
const androidDir = path.join(ROOT, 'android')
if (fs.existsSync(androidDir)) {
  fs.writeFileSync(
    path.join(androidDir, 'version.properties'),
    `# Generated by scripts/build-version.mjs from package.json — do not edit by hand.\nversionName=${manifest.version}\nversionCode=${versionCode}\n`,
  )
}

console.log(`[version] ${manifest.version} (versionCode ${versionCode}) → public/app/version.json, android/version.properties`)
